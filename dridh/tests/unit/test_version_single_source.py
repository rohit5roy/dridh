"""The Dridh version is set in exactly one place: ``src/dridh/__init__.py``. Everything else reads it."""

from __future__ import annotations

import json
import re
import runpy
import tomllib
from pathlib import Path

import dridh

ROOT = Path(__file__).resolve().parents[2]


def test_pyproject_takes_the_version_from_init() -> None:
    project = tomllib.loads((ROOT / "pyproject.toml").read_text(encoding="utf-8"))
    assert "version" not in project["project"] and "version" in project["project"]["dynamic"]
    assert project["tool"]["hatch"]["version"]["path"] == "src/dridh/__init__.py"


def test_version_script_reads_the_same_value() -> None:
    assert runpy.run_path(str(ROOT / "scripts" / "version.py"))["version"]() == dridh.__version__


def test_packaged_plugin_carries_the_dridh_version() -> None:
    packaged = ROOT / "src" / "dridh" / "assets" / "plugin" / "dridh-bridge" / "package.json"
    if packaged.is_file():  # generated by scripts/build_assets.py (CI runs it before the tests)
        semver = runpy.run_path(str(ROOT / "scripts" / "version.py"))["semver"]
        assert json.loads(packaged.read_text(encoding="utf-8"))["version"] == semver(dridh.__version__)


def test_no_other_source_file_sets_a_version_literal() -> None:
    pattern = re.compile(r'^\s*(__version__|version)\s*=\s*"\d+\.\d+\.\d+(rc\d+)?"', re.MULTILINE)
    offenders = [str(p.relative_to(ROOT)) for p in (ROOT / "src").rglob("*.py")
                 if p.name != "__init__.py" or p.parent.name != "dridh"
                 if pattern.search(p.read_text(encoding="utf-8"))]
    assert offenders == []
