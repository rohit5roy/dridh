"""Project-local Dridh workspace state under ``.opencode/dridh/``.

The workspace is bound to one project root. ``workspace.json`` records the
schema version, the workspace ID and the project root, so a state database
copied from another project is rejected rather than merged.
"""

from __future__ import annotations

import json
import os
import tempfile
import uuid
from dataclasses import dataclass
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

import dridh
from dridh.common.errors import DridhError, ErrorCode
from dridh.config.dridh_yaml import CONFIG_FILENAME, create_default_config, save_config
from dridh.workspace.paths import validate_workspace_root

WORKSPACE_DIR = Path(".opencode") / "dridh"


def discover_workspace_root(start: Path) -> Path:
    """The root a command acts on when no --workspace is given.

    The nearest directory at or above ``start`` that holds a Dridh workspace (so commands work from any subdirectory),
    otherwise the nearest Git root, otherwise ``start`` itself. Symbolic links are resolved first, so one workspace has
    one identity.
    """

    current = Path(start).expanduser().resolve()
    for candidate in (current, *current.parents):
        if (candidate / WORKSPACE_DIR / "workspace.json").is_file():
            return candidate
    for candidate in (current, *current.parents):
        if (candidate / ".git").exists():
            return candidate
    return current
WORKSPACE_MODES = ("new", "existing")


def suggest_mode(project_root: str | Path) -> str:
    """A hint only: a Git repository suggests an existing codebase. Never a substitute for asking."""
    return "existing" if (Path(project_root) / ".git").exists() else "new"


def workspace_exists(project_root: str | Path) -> bool:
    return (Path(project_root) / WORKSPACE_DIR / "workspace.json").is_file()
WORKSPACE_SCHEMA = "dridh.workspace"
WORKSPACE_SCHEMA_VERSION = 1
SUBDIRECTORIES = ("state", "artifacts", "reports", "evidence", "logs")
GITIGNORE = "# Generated by Dridh. Runtime state and logs are never committed.\nstate/\nlogs/\n*.tmp\n"


@dataclass(frozen=True)
class WorkspaceInfo:
    project_root: Path
    root: Path
    workspace_id: str
    schema_version: int
    created_at: str
    mode: str = "new"

    @property
    def state_db(self) -> Path:
        return self.root / "state" / "dridh.sqlite"

    def artifact_dir(self, workflow_id: str) -> Path:
        return self.root / "artifacts" / workflow_id

    def report_path(self, workflow_id: str) -> Path:
        return self.root / "reports" / f"{workflow_id}.md"

    def to_dict(self) -> dict[str, Any]:
        return {
            "project_root": str(self.project_root),
            "workspace_root": str(self.root),
            "workspace_id": self.workspace_id,
            "schema_version": self.schema_version,
            "mode": self.mode,
            "created_at": self.created_at,
        }


def _utc_now() -> str:
    return datetime.now(UTC).isoformat(timespec="seconds")


def _atomic_write_json(path: Path, payload: dict[str, Any]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    descriptor, temporary = tempfile.mkstemp(prefix=f".{path.name}.", suffix=".tmp", dir=path.parent)
    try:
        with os.fdopen(descriptor, "w", encoding="utf-8") as handle:
            json.dump(payload, handle, indent=2, sort_keys=True)
            handle.write("\n")
            handle.flush()
            os.fsync(handle.fileno())
        os.replace(temporary, path)
    except BaseException:
        try:
            os.unlink(temporary)
        except FileNotFoundError:
            pass
        raise


def _read_descriptor(path: Path) -> dict[str, Any]:
    try:
        payload = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        raise DridhError(
            ErrorCode.STATE_CORRUPT,
            "The Dridh workspace descriptor is unreadable.",
            details=(str(path),),
            recovery="Keep the file for diagnosis. Restore it from version control or a backup, or reinitialise the workspace.",
        ) from None
    if not isinstance(payload, dict):
        raise DridhError(ErrorCode.STATE_CORRUPT, "The Dridh workspace descriptor is not an object.", details=(str(path),))
    if payload.get("schema") != WORKSPACE_SCHEMA:
        raise DridhError(ErrorCode.STATE_CORRUPT, "The file is not a Dridh workspace descriptor.", details=(str(path),))
    if payload.get("schema_version") != WORKSPACE_SCHEMA_VERSION:
        raise DridhError(
            ErrorCode.SCHEMA_UNSUPPORTED,
            "The workspace schema version is not supported by this Dridh runtime.",
            details=(f"found {payload.get('schema_version')}, supported {WORKSPACE_SCHEMA_VERSION}",),
        )
    return payload


def _info(project_root: Path, root: Path, payload: dict[str, Any]) -> WorkspaceInfo:
    recorded_root = payload.get("project_root")
    if recorded_root != str(project_root):
        raise DridhError(
            ErrorCode.STATE_CORRUPT,
            "The workspace descriptor belongs to a different project root.",
            details=(f"recorded: {recorded_root}", f"requested: {project_root}"),
            recovery="Initialise a separate workspace for this project. Dridh never shares state between projects.",
        )
    try:
        workspace_id = str(uuid.UUID(str(payload["workspace_id"])))
    except (KeyError, ValueError, TypeError):
        raise DridhError(ErrorCode.STATE_CORRUPT, "The workspace descriptor has no valid workspace ID.") from None
    return WorkspaceInfo(
        project_root=project_root,
        root=root,
        workspace_id=workspace_id,
        schema_version=WORKSPACE_SCHEMA_VERSION,
        created_at=str(payload.get("created_at", "")),
        mode=str(payload.get("mode", "new")),
    )


def init_workspace(project_root: str | Path, *, mode: str | None = None, workspace_override: str | Path | None = None) -> tuple[WorkspaceInfo, bool]:
    """Create or validate the workspace. Returns the workspace and whether it was created."""

    if workspace_override is not None:
        root_path = validate_workspace_root(workspace_override)
    else:
        root_path = validate_workspace_root(project_root)
    if mode is not None and mode not in WORKSPACE_MODES:
        raise DridhError(ErrorCode.VALIDATION_FAILED, f"mode must be one of: {', '.join(WORKSPACE_MODES)}.", details=(str(mode),))
    workspace_root = root_path / WORKSPACE_DIR
    descriptor = workspace_root / "workspace.json"
    config_path = workspace_root / CONFIG_FILENAME
    created = False
    if descriptor.exists():
        info = _info(root_path, workspace_root, _read_descriptor(descriptor))
        if not config_path.exists():
            cfg = create_default_config(root_path, mode=info.mode, workspace_id=info.workspace_id)
            save_config(config_path, cfg)
    else:
        created = True
        if mode is None:
            # Library callers that cannot ask (for example the bridge) get the Git-based hint; the CLI never
            # relies on this and the bridge reports `mode_inferred`.
            mode = suggest_mode(root_path)
        payload = {
            "schema": WORKSPACE_SCHEMA,
            "schema_version": WORKSPACE_SCHEMA_VERSION,
            "workspace_id": str(uuid.uuid4()),
            "project_root": str(root_path),
            "mode": mode,
            "created_at": _utc_now(),
            "dridh_version": dridh.__version__,
        }
        for name in SUBDIRECTORIES:
            (workspace_root / name).mkdir(parents=True, exist_ok=True)
        gitignore = workspace_root / ".gitignore"
        if not gitignore.exists():
            gitignore.write_text(GITIGNORE, encoding="utf-8")
        _atomic_write_json(descriptor, payload)
        info = _info(root_path, workspace_root, payload)
        cfg = create_default_config(root_path, mode=mode, workspace_id=info.workspace_id)
        save_config(workspace_root / CONFIG_FILENAME, cfg)
    for name in SUBDIRECTORIES:
        (workspace_root / name).mkdir(parents=True, exist_ok=True)
    return info, created


def open_workspace(project_root: str | Path) -> WorkspaceInfo:
    """Open an initialised workspace. Never creates anything."""

    root_path = validate_workspace_root(project_root)
    workspace_root = root_path / WORKSPACE_DIR
    descriptor = workspace_root / "workspace.json"
    if not descriptor.is_file():
        raise DridhError(
            ErrorCode.WORKSPACE_NOT_FOUND,
            "The project has no Dridh workspace.",
            details=(str(workspace_root),),
            recovery="Run dridh init in the project root first.",
        )
    return _info(root_path, workspace_root, _read_descriptor(descriptor))
